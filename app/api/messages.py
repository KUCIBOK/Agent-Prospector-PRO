"""
Message routes — outreach queue and manual tracking.
"""

import logging

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session
from sqlmodel import func, select

from app.db import get_session
from app.models import Message, MessageOutcome, MessageStatus, Prospect
from app.schemas import (
    MessageCreate,
    MessageResponse,
    MessagesQueueResponse,
    MessageUpdate,
)

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/messages", tags=["messages"])


@router.get("", response_model=MessagesQueueResponse)
def list_messages(
    session: Session = Depends(get_session),
    status: MessageStatus | None = None,
    outcome: MessageOutcome | None = None,
    persona: str | None = None,
    page: int = Query(1, ge=1),
    page_size: int = Query(20, ge=1, le=100),
) -> MessagesQueueResponse:
    """
    List outreach messages — sorted by prospect priority.

    Query parameters:
    - status: Filter by status (DRAFT, SENT)
    - outcome: Filter by outcome (REPLIED, MEETING, etc.)
    - persona: Filter by persona (ART_ADVISOR, CURATOR)
    - page, page_size: Pagination
    """
    # Build query
    query = select(Message).join(Prospect)

    if status:
        query = query.where(Message.status == status)
    if outcome:
        query = query.where(Message.outcome == outcome)
    if persona:
        query = query.where(Message.persona == persona)

    # Sort by prospect priority (P1 first)
    query = query.order_by(Prospect.priority.asc()).order_by(Message.generated_at.desc())

    # Count
    total = session.scalar(select(func.count()).select_from(Message).where(query.whereclause))

    # Status counts
    pending = session.scalar(
        select(func.count()).select_from(Message).where(Message.status == MessageStatus.DRAFT)
    )
    sent = session.scalar(
        select(func.count()).select_from(Message).where(Message.status == MessageStatus.SENT)
    )
    replied = session.scalar(
        select(func.count()).select_from(Message).where(Message.outcome == MessageOutcome.REPLIED)
    )

    # Paginate
    offset = (page - 1) * page_size
    messages = session.exec(query.offset(offset).limit(page_size)).all()

    return MessagesQueueResponse(
        total=total,
        pending=pending or 0,
        sent=sent or 0,
        replied=replied or 0,
        items=[MessageResponse.model_validate(m) for m in messages],
    )


@router.get("/{message_id}", response_model=MessageResponse)
def get_message(message_id: int, session: Session = Depends(get_session)) -> MessageResponse:
    """Get a specific message by ID."""
    message = session.get(Message, message_id)
    if not message:
        raise HTTPException(status_code=404, detail="Message not found")
    return MessageResponse.model_validate(message)


@router.post("", response_model=MessageResponse, status_code=201)
def create_message(
    message_in: MessageCreate,
    session: Session = Depends(get_session),
) -> MessageResponse:
    """Create a new outreach message (generated by system or manually)."""
    # Verify prospect exists
    prospect = session.get(Prospect, message_in.prospect_id)
    if not prospect:
        raise HTTPException(status_code=404, detail="Prospect not found")

    message = Message(**message_in.model_dump())
    session.add(message)
    session.commit()
    session.refresh(message)

    logger.info(f"✅ Created message for prospect {message_in.prospect_id}: {message.id}")
    return MessageResponse.model_validate(message)


@router.patch("/{message_id}", response_model=MessageResponse)
def update_message(
    message_id: int,
    message_in: MessageUpdate,
    session: Session = Depends(get_session),
) -> MessageResponse:
    """Update message status or outcome (manual tracking)."""
    message = session.get(Message, message_id)
    if not message:
        raise HTTPException(status_code=404, detail="Message not found")

    update_data = message_in.model_dump(exclude_unset=True)
    for key, value in update_data.items():
        setattr(message, key, value)

    session.add(message)
    session.commit()
    session.refresh(message)

    logger.info(
        f"✅ Updated message {message_id}: status={message.status}, outcome={message.outcome}"
    )
    return MessageResponse.model_validate(message)


@router.delete("/{message_id}", status_code=204)
def delete_message(message_id: int, session: Session = Depends(get_session)) -> None:
    """Delete a message (use sparingly — audit trail)."""
    message = session.get(Message, message_id)
    if not message:
        raise HTTPException(status_code=404, detail="Message not found")

    session.delete(message)
    session.commit()

    logger.info(f"✅ Deleted message {message_id}")


@router.get("/queue/draft")
def get_draft_queue(session: Session = Depends(get_session)):
    """Get all DRAFT messages ready to send (sorted by priority)."""
    query = (
        select(Message, Prospect)
        .join(Prospect)
        .where(Message.status == MessageStatus.DRAFT)
        .order_by(Prospect.priority.asc())
    )

    results = session.exec(query).all()
    messages = [result[0] for result in results]

    return {
        "total": len(messages),
        "messages": [MessageResponse.model_validate(m) for m in messages],
    }
